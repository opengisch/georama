"""Every route of Georama, with the status each persona gets for each HTTP method.

`test_routes.py` checks this matrix against the URL configuration, then calls every route x
method x persona on the global organisation, with an empty JSON payload for the writes. The
addressed objects are not public, the viewer has the view permission on the layers and themes.

The other modules of `tests/api` reuse this matrix: the CRUD tests write on the routes the
superuser can write on, the isolation tests expect the status of the superuser on the objects
of its organisation, the public content tests read the routes listing the public objects.

Routes are keyed by their namespaced name: the variants with a format suffix generated by
`DefaultRouter` share the name of their route. HEAD and OPTIONS are left out, every view
answers them. The admin, allauth (`accounts/`) and silk routes are not listed.

A status is declared in one of four ways:

- `200`: the status an endpoint of this kind usually answers;
- `Intended(404, reason)`: a status chosen on purpose, unlike what an endpoint of this kind
  usually answers;
- `Rule(405, reason)`: the status once a rule of Georama is enforced. The code works, but
  allows what the domain forbids, e.g. editing an object integrated from a QGIS project;
- `Bug(200, reason)`: the status once a defect of the code is fixed, e.g. a server error.

The rules and the bugs are strict xfails, whose reason starts with `rule:` or `bug:`.
"""

from collections.abc import Iterable
from dataclasses import dataclass

import pytest

from tests.fixtures.personas import PERSONAS


@dataclass(frozen=True)
class Intended:
    """A status chosen on purpose, unlike what an endpoint of this kind usually answers: the
    test passes, the reason documents the choice.
    """

    status: int
    reason: str


@dataclass(frozen=True)
class Rule:
    """Status expected once a rule of the domain is enforced: the code works, but allows what
    Georama forbids. The test is a strict xfail until then.
    """

    status: int
    reason: str


@dataclass(frozen=True)
class Bug:
    """Status expected once a defect of the code is fixed: the test is a strict xfail until
    then.
    """

    status: int
    reason: str


Status = int | Intended | Rule | Bug


def xfail(known: Iterable[Rule | Bug]) -> list:
    """The marks of a test case hitting the `known` rules and bugs: a strict xfail giving
    their reasons, none without.
    """
    reason = "; ".join(
        f"{'rule' if isinstance(status, Rule) else 'bug'}: {status.reason}" for status in known
    )
    return [pytest.mark.xfail(strict=True, reason=reason)] if reason else []


def expected(status: Status) -> tuple[int, list]:
    """The status expected and the marks of its test case: a strict xfail for a rule not
    enforced yet or a known bug.
    """
    if isinstance(status, Rule | Bug):
        return status.status, xfail([status])
    if isinstance(status, Intended):
        return status.status, []
    return status, []


# the status of each persona, by method
Statuses = dict[str, dict[str, Status]]


def route(**methods: dict[str, Status]) -> Statuses:
    """The status of each persona, by method: `route(get=allow(...), post=allow(...))`."""
    return methods


EVERYONE = set(PERSONAS)
