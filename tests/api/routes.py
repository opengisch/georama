"""Every route of Georama, with the status each persona gets for each HTTP method, and how the
isolation of the organisations is checked on it.

`test_routes.py` checks this matrix against the URL configuration, then calls every route x
method x persona on the global organisation, with an empty JSON payload for the writes. The
addressed objects are not public, the viewer has the view permission on the layers and themes.

`isolation/test_isolation.py` deduces the isolation check of the viewsets on an organisational
model, and fails on the other routes until their `isolation` is declared, see
`isolation/checks.py`.

Routes are keyed by their namespaced name: the variants with a format suffix generated by
`DefaultRouter` share the name of their route. HEAD and OPTIONS are left out, every view
answers them. The admin, allauth (`accounts/`) and silk routes are not listed.
"""

