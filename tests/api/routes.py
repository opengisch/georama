@dataclass(frozen=True)
class Bug:
    """Status expected once a known bug is fixed: the test is a strict xfail until then."""

    status: int
    reason: str


def expected(status: int | Bug) -> tuple[int, list]:
    """The status expected and the marks of its test case: a strict xfail for a known bug."""
    if isinstance(status, Bug):
        return status.status, [pytest.mark.xfail(strict=True, reason=status.reason)]
    return status, []


@dataclass(frozen=True)
class RouteDeclaration:
    # the status of each persona, by method
    methods: dict[str, dict[str, int | Bug]]
    # None when deduced from the viewset
    isolation: Isolation | None = None


def route(isolation: Isolation | None = None, **methods: dict[str, int | Bug]) -> RouteDeclaration:
    return RouteDeclaration(methods, isolation)


